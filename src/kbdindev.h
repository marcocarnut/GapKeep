//
// kbdindev.h
//
// Feeds Circle's USB keyboard into LVGL as a keypad input device.
//
// The keyboard runs in Circle's "mixed" mode: the cooked handler delivers
// characters and VT100-style escape sequences (with auto-repeat and the
// keymap applied), the raw handler gives us modifier state (Shift, Ctrl,
// Alt, GUI). Each key press becomes a TGkKey, which is queued, offered to an
// optional key hook (the running app's ui.onKey handler) and then, if not
// consumed, delivered to LVGL as one press/release pair.
//
// The GUI ("Windows"/Super) key is the Home key: it asks the system to return
// to the launcher. That request is raised from interrupt context, so it must
// only set flags (see SetHomeHandler).
//
// The layout (runtime/keylayout.h) is Circle's keymap, loaded into the
// keyboard when it is attached and whenever the layout changes; dead keys
// are composed here. Characters reach LVGL and the key hook as UTF-8.
//
// SPDX-License-Identifier: GPL-3.0-or-later
//
#ifndef _kbdindev_h
#define _kbdindev_h

#include <circle/usb/usbkeyboard.h>
#include <circle/types.h>
#include <lvgl/lvgl.h>
#include "runtime/keylayout.h"

#define GK_MOD_SHIFT	(1 << 0)
#define GK_MOD_CTRL	(1 << 1)
#define GK_MOD_ALT	(1 << 2)

struct TGkKey
{
	u32 nLVKey;		// LVGL key code: LV_KEY_*, or a character's UTF-8
				// bytes, the first in the lowest byte (as
				// lv_textarea_add_char() takes them); 0: not for LVGL
	char Name[12];		// "a", "A", "ç" (UTF-8), "Enter", "ArrowUp", "F5", ...
	u8 nMods;		// GK_MOD_*
	boolean bRepeat;	// generated by auto-repeat, not by a key going down
};

class CKeyboardIndev
{
public:
	typedef boolean TKeyHook (const TGkKey &rKey, void *pParam);	// TRUE: consumed
	typedef void THomeHandler (void *pParam);			// IRQ context!

public:
	CKeyboardIndev (void);

	// Creates the LVGL keypad device. Call after CLVGL::Initialize().
	void Initialize (void);

	// Call from the main loop after USB plug-and-play updates.
	void Update (boolean bPlugAndPlayUpdated);

	// Keys are delivered to widgets in this group.
	void SetGroup (lv_group_t *pGroup);
	lv_group_t *GetGroup (void) const;

	void SetKeyHook (TKeyHook *pHook, void *pParam);
	void SetHomeHandler (THomeHandler *pHandler, void *pParam);

	// Drop queued keys (e.g. when switching apps).
	void Flush (void);

	// The simulator in a browser: the characters it hands over were composed
	// by the browser, with the computer's own layout and dead keys, so
	// GapKeep's dead keys must not compose them again. Set around Pressed().
	void SetComposed (boolean bComposed)	{ m_bComposed = bComposed; }

private:
	static void KeyPressedHandler (const char *pString);
	static void KeyStatusHandlerRaw (unsigned char ucModifiers, const unsigned char RawKeys[6]);
	static void KeyboardRemovedHandler (CDevice *pDevice, void *pContext);
	static void ReadCallback (lv_indev_t *pIndev, lv_indev_data_t *pData);

	void Enqueue (const TGkKey &rKey);
	// a special key into *pKey, or a character into *pChar (Unicode)
	boolean Translate (const char *pString, TGkKey *pKey, u32 *pChar) const;
	void EnqueueChar (u32 nChar, const TGkKey &rTemplate);

private:
	CUSBKeyboardDevice *m_pKeyboard;
	lv_indev_t *m_pIndev;

	volatile u8 m_nRawModifiers;	// last USB HID modifier byte
	u8 m_RawKeys[6];		// last USB HID key codes
	volatile boolean m_bNewPress;	// a key went down since the last character
	boolean m_bGUIDown;

	CGkDeadKeys m_DeadKeys;		// used in interrupt context
	boolean m_bComposed;		// SetComposed()
	unsigned m_nLayoutGeneration;	// of the keymap loaded into m_pKeyboard

	// Single producer (USB interrupt context) / single consumer (main loop).
	static const unsigned QueueSize = 64;	// power of two
	TGkKey m_Queue[QueueSize];
	volatile unsigned m_nHead;
	volatile unsigned m_nTail;

	u32 m_nPressedKey;		// key currently reported as pressed, 0 if none
	lv_group_t *m_pPressedGroup;	// focus at the time of the press
	lv_obj_t *m_pPressedObj;	// (compared only, never dereferenced)

	TKeyHook *m_pKeyHook;
	void *m_pKeyHookParam;
	THomeHandler *m_pHomeHandler;
	void *m_pHomeParam;

	static CKeyboardIndev *s_pThis;
};

#endif
