#!/usr/bin/env python3
"""
Wrap QuickJS's own test scripts (third_party/quickjs/tests) into a module
for the test-only "qjstests" app, which runs them on the target.

Usage: make_qjstests.py <quickjs-dir> <output.js>

SPDX-License-Identifier: GPL-3.0-or-later
"""
import json
import os
import sys

SUITES = ['test_language.js', 'test_builtin.js', 'test_bigint.js', 'test_closure.js', 'test_loop.js']


def main():
    qjs, out = sys.argv[1], sys.argv[2]
    parts = ['// Generated by tools/make_qjstests.py - do not edit.', 'export const suites = {']
    for name in SUITES:
        with open(os.path.join(qjs, 'tests', name), encoding='utf-8') as f:
            parts.append('  %s: %s,' % (json.dumps(name), json.dumps(f.read())))
    parts.append('};')
    data = '\n'.join(parts) + '\n'
    try:
        if open(out, encoding='utf-8').read() == data:
            return
    except OSError:
        pass
    with open(out, 'w', encoding='utf-8') as f:
        f.write(data)


if __name__ == '__main__':
    main()
