#!/usr/bin/env python3
"""
Embeds a system module written in JavaScript (src/runtime/i18n.js, the
module "gk:i18n") into the kernel and the simulator, as a C string:

    const char <symbol>[] = "...";
    const unsigned <symbol>_size = <bytes>;

The runtime compiles it when an app imports the module. The output is only
rewritten when it changes, so it rebuilds only what needs it.

Usage: embed_js.py <output.c> <symbol> <module.js>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bundle_apps import c_string  # noqa: E402


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out, symbol, src = sys.argv[1:]
    with open(src, 'rb') as f:
        data = f.read()
    data.decode('utf-8')        # must be UTF-8
    if b'\0' in data:
        sys.exit('embed_js: %s contains NUL bytes' % src)
    text = ('/* Generated by tools/embed_js.py from %s - do not edit. */\n'
            'const char %s[] =\n\t%s;\n'
            'const unsigned %s_size = %d;\n'
            % (os.path.basename(src), symbol, c_string(data), symbol, len(data)))
    try:
        with open(out) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as f:
        f.write(text)


if __name__ == '__main__':
    main()
