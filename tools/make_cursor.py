#!/usr/bin/env python3
"""
Draw zerogap's mouse pointer and write it as C (src/runtime/cursor.c).

An arrow with a white body, a dark outline and a soft shadow, drawn 8 times
larger and scaled down, so its edges are smooth (anti-aliased) rather than
the stair-stepped bitmap Circle's LVGL addon brings. The output is
deterministic and checked in; rerun after changing the shape:

    python3 tools/make_cursor.py > src/runtime/cursor.c

Needs Pillow; runs on the development machine only.
"""
from PIL import Image, ImageDraw, ImageFilter

SS = 8                      # supersampling
MARGIN = 2                  # px around the arrow for outline and shadow
OUTLINE = 1.3               # px
SHADOW_OFFSET = (1.0, 1.5)  # px
SHADOW_BLUR = 1.2           # px
SHADOW_ALPHA = 0.35

# the arrow, tip at (0, 0), in px
ARROW = [(0, 0), (0, 16.2), (3.9, 12.5), (6.6, 18.6), (9.1, 17.5),
         (6.5, 11.6), (11.6, 11.6)]


def mask(points, grow, offset=(0.0, 0.0)):
    """The arrow as an 8-bit mask at SS x scale, grown by `grow` px."""
    w, h = size
    m = Image.new('L', (w * SS, h * SS), 0)
    d = ImageDraw.Draw(m)
    pts = [((x + MARGIN + offset[0]) * SS, (y + MARGIN + offset[1]) * SS) for x, y in points]
    d.polygon(pts, fill=255)
    if grow > 0:
        d.line(pts + [pts[0]], fill=255, width=round(2 * grow * SS), joint='curve')
        r = grow * SS
        for x, y in pts:     # round corners
            d.ellipse([x - r, y - r, x + r, y + r], fill=255)
    return m


def down(m):
    return m.resize(size, Image.BOX)


xs = [x for x, _ in ARROW]
ys = [y for _, y in ARROW]
size = (int(max(xs) + 2 * MARGIN + 1), int(max(ys) + 2 * MARGIN + 1))

body = down(mask(ARROW, 0))
outer = down(mask(ARROW, OUTLINE))
shadow = down(mask(ARROW, OUTLINE, SHADOW_OFFSET)).filter(ImageFilter.GaussianBlur(SHADOW_BLUR))
shadow = shadow.point(lambda a: round(a * SHADOW_ALPHA))

# compose: shadow, then the dark outline, then the white body
img = Image.new('RGBA', size, (0, 0, 0, 0))
img = Image.alpha_composite(img, Image.merge('RGBA', [Image.new('L', size, 0)] * 3 + [shadow]))
dark = Image.merge('RGBA', [Image.new('L', size, 24)] * 3 + [outer])
img = Image.alpha_composite(img, dark)
white = Image.merge('RGBA', [Image.new('L', size, 255)] * 3 + [body])
img = Image.alpha_composite(img, white)

w, h = size
px = img.tobytes()
print('/* Generated by tools/make_cursor.py - do not edit. */')
print('#include "cursor.h"')
print()
print('/* %d x %d, LVGL ARGB8888 (B, G, R, A in memory), tip at (%d, %d) */' % (w, h, MARGIN, MARGIN))
print('static const unsigned char CursorPixels[%d] = {' % (w * h * 4))
for y in range(h):
    row = []
    for x in range(w):
        r, g, b, a = px[(y * w + x) * 4:(y * w + x) * 4 + 4]
        row += [b, g, r, a]
    print('\t' + ','.join(str(v) for v in row) + ',')
print('};')
print()
print('const lv_image_dsc_t gk_cursor_image = {')
print('\t.header = {')
print('\t\t.magic = LV_IMAGE_HEADER_MAGIC,')
print('\t\t.cf = LV_COLOR_FORMAT_ARGB8888,')
print('\t\t.w = %d,' % w)
print('\t\t.h = %d,' % h)
print('\t\t.stride = %d,' % (w * 4))
print('\t},')
print('\t.data_size = sizeof CursorPixels,')
print('\t.data = CursorPixels,')
print('};')
print()
print('const int gk_cursor_hot_x = %d;' % MARGIN)
print('const int gk_cursor_hot_y = %d;' % MARGIN)
