#!/usr/bin/env python3
"""
Test pictures for the synthetic camera of test builds (make TEST=1): the
colour QR codes of tests/colorqr, run-length encoded into a C file, so that
"#camera picture <name>" (src/testshot.h) shows one to the camera in QEMU
and on the rig, as "camera picture <file>" does in the simulator.

Usage: make_test_pictures.py out.c tests/colorqr/*.png
Writes out.c only if it changed. Needs Python's PIL.
"""
import os
import sys


def main():
    from PIL import Image
    out, pngs = sys.argv[1], sys.argv[2:]
    lines = ['/* Generated by tools/make_test_pictures.py: do not edit. */',
             '#include "../testpictures.h"', '']
    table = []
    for n, path in enumerate(sorted(pngs)):
        im = Image.open(path).convert('RGB')
        w, h = im.size
        data = im.tobytes()
        # runs: count (1-255), R, G, B
        rle = bytearray()
        i = 0
        while i < len(data):
            px = data[i:i + 3]
            count = 1
            while count < 255 and data[i + 3 * count:i + 3 * count + 3] == px:
                count += 1
            rle += bytes([count]) + px
            i += 3 * count
        lines.append('static const unsigned char picture%d[%d] = {' % (n, len(rle)))
        for j in range(0, len(rle), 24):
            lines.append('\t' + ', '.join(str(b) for b in rle[j:j + 24]) + ',')
        lines.append('};')
        name = os.path.splitext(os.path.basename(path))[0]
        table.append('\t{ "%s", %d, %d, picture%d, sizeof picture%d },' % (name, w, h, n, n))
    lines.append('')
    lines.append('const TZgTestPicture zg_test_pictures[] = {')
    lines += table
    lines.append('\t{ 0, 0, 0, 0, 0 }')
    lines.append('};')
    data = '\n'.join(lines) + '\n'
    try:
        with open(out) as f:
            if f.read() == data:
                return
    except OSError:
        pass
    with open(out, 'w') as f:
        f.write(data)


if __name__ == '__main__':
    main()
